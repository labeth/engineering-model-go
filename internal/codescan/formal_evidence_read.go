package codescan

// The one reader of formal (Quint) evidence files (ADR-EMG-042). The codescan
// verification inference, the trace matrix, the Gemara exporter and the MCP
// tools all read test-results/quint-formal.json through this file, so the
// stale rule, the status mapping and the directories scanned cannot drift
// apart.
//
// Trust model: committed evidence is unsigned. Anyone who can edit the
// repository can write an evidence file that names a module and its sha256.
// The reader therefore only counts an entry as current when the module it
// names is a regular file that really lies inside the model root, is a
// generated Quint module of the machine the entry names and still has the
// recorded hash. That keeps stale and hand-made entries out; it does not
// prove that Quint ran, so CI must rerun `engquint check` and compare.

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// FormalEvidenceFile is the name of the evidence file engquint check writes
// into test-results/. The codescan package must not import the exporter, so
// the layout is read by name: a results array whose entries carry requirement,
// status, machine, invariant, mode, qntFile (relative to the model root),
// qntSha256 and notes.
const FormalEvidenceFile = "quint-formal.json"

// FormalGeneratedHeader starts the first line of every generated Quint module,
// the machine ID follows. It must equal quint.GeneratedHeader of
// internal/export/quint, which this package may not import; the root package
// test TestFormalGeneratedHeaderMatchesGenerator fails if the two differ.
const FormalGeneratedHeader = "// Generated by engineering-model-go from "

// Formal results: the per-entry and requirement-level result values.
const (
	// FormalPass is a current passing result: analysis evidence.
	FormalPass = "pass"
	// FormalFailed is a current failing result (fail, blocked, partial, flaky).
	FormalFailed = "failed"
	// FormalStale is a result whose module is missing, changed, outside the
	// model root, not a generated module or unreadable: no evidence.
	FormalStale = "stale"
	// FormalNotRun is any other recorded status: no evidence.
	FormalNotRun = "not-run"
)

const (
	// maxFormalModuleBytes caps what is read of a module named by an evidence
	// entry. A generated module is a few kilobytes.
	maxFormalModuleBytes = 4 << 20
	// maxFormalEvidenceBytes caps what is read of an evidence file.
	maxFormalEvidenceBytes = 16 << 20
)

// FormalEntry is one results[] entry of a formal evidence file, evaluated
// against the module on disk.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE, FU-ALLOCATION-TRACE
// TRLC-LINKS: REQ-EMG-145, REQ-EMG-146
type FormalEntry struct {
	Requirement string
	Machine     string
	Invariant   string
	// Mode is run, verify or run+verify as engquint recorded it.
	Mode string
	// Status is the recorded status normalised by NormalizeResultStatus; it is
	// what was recorded, whether or not the entry is stale.
	Status string
	// Result is FormalPass, FormalFailed, FormalStale or FormalNotRun.
	Result    string
	QntFile   string
	QntSha256 string
	// Evidence is the evidence file, relative to the model root, with slashes.
	Evidence string
	// Notes holds the recorded notes, or the stale reason with a hint to rerun.
	Notes string
	// StaleReason is why the entry is stale; empty for a current entry.
	StaleReason string
}

// VerificationResultRoots returns the existing directories the verification
// inference scans for result files: <baseDir>/test-results and, when
// codeRootOption is set, test-results beside the code root (a relative code
// root is relative to baseDir). Every reader of formal evidence uses this list.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE
// TRLC-LINKS: REQ-EMG-146
func VerificationResultRoots(baseDir, codeRootOption string) []string {
	return uniqueExistingDirs(append(
		[]string{filepath.Join(baseDir, "test-results")},
		inferredSiblingDirs(baseDir, codeRootOption, "test-results")...,
	))
}

// FormalEvidenceFiles lists the formal evidence files under the verification
// result roots of VerificationResultRoots, as paths relative to baseDir with
// slashes, sorted and without duplicates.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE
// TRLC-LINKS: REQ-EMG-146
func FormalEvidenceFiles(baseDir, codeRootOption string) []string {
	seen := map[string]bool{}
	var files []string
	for _, root := range VerificationResultRoots(baseDir, codeRootOption) {
		_ = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || !isFormalEvidencePath(path) {
				return nil
			}
			rel, relErr := filepath.Rel(baseDir, path)
			if relErr != nil {
				rel = path
			}
			if rel = filepath.ToSlash(rel); !seen[rel] {
				seen[rel] = true
				files = append(files, rel)
			}
			return nil
		})
	}
	sort.Strings(files)
	return files
}

// ReadFormalEvidence reads the evidence files (paths relative to baseDir) and
// evaluates each entry against the module it names; see FormalStaleReason for
// the rules. A current entry is FormalPass or FormalFailed by its normalised
// status (fail, blocked, partial and flaky are failed), a stale one is
// FormalStale and any other status is FormalNotRun. An unreadable or invalid
// file contributes nothing (the verification inference reports it as
// verification.formal_unreadable). The result is sorted by requirement,
// machine, invariant, evidence file, module, mode and result.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE, FU-ALLOCATION-TRACE
// TRLC-LINKS: REQ-EMG-145, REQ-EMG-146
func ReadFormalEvidence(baseDir string, files []string) []FormalEntry {
	var out []FormalEntry
	modules := newFormalModules(baseDir)
	for _, rel := range files {
		entries, err := readFormalEvidenceFile(modules, filepath.Join(baseDir, filepath.FromSlash(rel)), filepath.ToSlash(rel))
		if err != nil {
			continue
		}
		out = append(out, entries...)
	}
	sort.SliceStable(out, func(i, j int) bool {
		a, b := out[i], out[j]
		switch {
		case a.Requirement != b.Requirement:
			return a.Requirement < b.Requirement
		case a.Machine != b.Machine:
			return a.Machine < b.Machine
		case a.Invariant != b.Invariant:
			return a.Invariant < b.Invariant
		case a.Evidence != b.Evidence:
			return a.Evidence < b.Evidence
		case a.QntFile != b.QntFile:
			return a.QntFile < b.QntFile
		case a.Mode != b.Mode:
			return a.Mode < b.Mode
		}
		return a.Result < b.Result
	})
	return out
}

// formalFileEntry is the JSON of one results[] entry.
type formalFileEntry struct {
	Requirement string `json:"requirement"`
	Status      string `json:"status"`
	Machine     string `json:"machine"`
	Invariant   string `json:"invariant"`
	Mode        string `json:"mode"`
	QntFile     string `json:"qntFile"`
	QntSha256   string `json:"qntSha256"`
	Notes       string `json:"notes"`
}

// errFormalNotJSON marks an evidence file that is not valid JSON.
var errFormalNotJSON = errors.New("formal evidence is not valid JSON")

// readFormalEvidenceFile reads one evidence file (path on disk, rel for the
// Evidence field) and evaluates its entries; entries without a requirement are
// skipped.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE
// TRLC-LINKS: REQ-EMG-145, REQ-EMG-146
func readFormalEvidenceFile(modules *formalModules, path, rel string) ([]FormalEntry, error) {
	data, err := readCappedFile(path, maxFormalEvidenceBytes)
	if err != nil {
		return nil, err
	}
	var file struct {
		Results []formalFileEntry `json:"results"`
	}
	if err := json.Unmarshal(data, &file); err != nil {
		return nil, fmt.Errorf("%w: %v", errFormalNotJSON, err)
	}
	var out []FormalEntry
	for _, e := range file.Results {
		req := strings.TrimSpace(e.Requirement)
		if req == "" {
			continue
		}
		entry := FormalEntry{
			Requirement: req, Machine: strings.TrimSpace(e.Machine), Invariant: strings.TrimSpace(e.Invariant),
			Mode: strings.TrimSpace(e.Mode), Status: NormalizeResultStatus(e.Status),
			QntFile: strings.TrimSpace(e.QntFile), QntSha256: strings.ToLower(strings.TrimSpace(e.QntSha256)),
			Evidence: rel, Notes: strings.TrimSpace(e.Notes),
		}
		switch entry.Status {
		case "pass":
			entry.Result = FormalPass
		case "fail", "blocked", "partial", "flaky":
			entry.Result = FormalFailed
		default:
			entry.Result = FormalNotRun
		}
		if reason := modules.staleReason(entry); reason != "" {
			entry.Result = FormalStale
			entry.StaleReason = reason
			entry.Notes = "stale: " + reason + "; rerun engquint check"
		}
		out = append(out, entry)
	}
	return out, nil
}

// FormalStaleReason returns why an entry is stale, or "" when it is current.
// An entry is current only when all of these hold:
//   - it records a qntFile and a qntSha256;
//   - qntFile is a local relative path (filepath.IsLocal: not rooted, no ..
//     element) that, with symbolic links resolved, still lies inside the
//     resolved model root, and names a regular file (no device, FIFO or
//     directory);
//   - the file is at most 4 MiB, and its first line starts with
//     FormalGeneratedHeader followed by the entry's machine (a generated Quint
//     module of that machine, not any file whose hash was written down);
//   - the sha256 of the file content with every CRLF replaced by LF equals
//     qntSha256, so a Windows checkout with core.autocrlf does not turn every
//     result stale.
//
// Anything else is stale and never an error. The hash rule (sha256 of the
// module after replacing CRLF with LF) is the one engquint check records.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE
// TRLC-LINKS: REQ-EMG-145
func FormalStaleReason(modelRoot string, entry FormalEntry) string {
	return newFormalModules(modelRoot).staleReason(entry)
}

// formalModule is what is known of one module file: its hash and header line,
// or the reason it cannot be trusted.
type formalModule struct {
	sha    string
	header string
	reason string
}

// formalModules evaluates modules relative to a model root and caches each.
type formalModules struct {
	root    string
	cache   map[string]formalModule
	rootErr error
	rootDir string
}

// newFormalModules returns an empty module cache for a model root.
//
// TRLC-LINKS: REQ-EMG-145
func newFormalModules(root string) *formalModules {
	m := &formalModules{root: root, cache: map[string]formalModule{}}
	m.rootDir, m.rootErr = filepath.EvalSymlinks(root)
	return m
}

// staleReason applies the rule of FormalStaleReason using the module cache.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE
// TRLC-LINKS: REQ-EMG-145
func (m *formalModules) staleReason(entry FormalEntry) string {
	file := strings.TrimSpace(entry.QntFile)
	want := strings.ToLower(strings.TrimSpace(entry.QntSha256))
	if file == "" || want == "" {
		return "the entry records no qntFile or qntSha256"
	}
	mod, ok := m.cache[file]
	if !ok {
		mod = m.load(file)
		m.cache[file] = mod
	}
	switch {
	case mod.reason != "":
		return mod.reason
	case !generatedModuleOf(mod.header, entry.Machine):
		return fmt.Sprintf("%s is not a generated Quint module of machine %s", file, textOr(entry.Machine, "(none)"))
	case mod.sha != want:
		return fmt.Sprintf("the sha256 of %s no longer matches the one the result was produced from", file)
	}
	return ""
}

// textOr returns s, or fallback when s is blank.
//
// TRLC-LINKS: REQ-EMG-145
func textOr(s, fallback string) string {
	if strings.TrimSpace(s) == "" {
		return fallback
	}
	return s
}

// generatedModuleOf reports whether header is the first line of a module
// generated from machine: the generated prefix, then the machine ID, then
// the end of the line or the trailer separator.
//
// TRLC-LINKS: REQ-EMG-145
func generatedModuleOf(header, machine string) bool {
	machine = strings.TrimSpace(machine)
	rest, ok := strings.CutPrefix(header, FormalGeneratedHeader)
	if !ok || machine == "" {
		return false
	}
	rest, ok = strings.CutPrefix(rest, machine)
	return ok && (rest == "" || rest[0] == ';' || rest[0] == ' ')
}

// load reads and hashes the module named by a qntFile of an evidence entry.
// Every failure becomes a reason, never an error.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE
// TRLC-LINKS: REQ-EMG-145
func (m *formalModules) load(file string) formalModule {
	native := filepath.FromSlash(file)
	if filepath.IsAbs(native) || filepath.VolumeName(native) != "" || strings.HasPrefix(file, "/") || strings.HasPrefix(file, `\`) || !filepath.IsLocal(native) {
		return formalModule{reason: fmt.Sprintf("qntFile %s is not a local path relative to the model root", file)}
	}
	if m.rootErr != nil {
		return formalModule{reason: fmt.Sprintf("module %s is missing", file)}
	}
	real, err := filepath.EvalSymlinks(filepath.Join(m.root, native))
	if err != nil {
		return formalModule{reason: fmt.Sprintf("module %s is missing", file)}
	}
	if rel, err := filepath.Rel(m.rootDir, real); err != nil || !filepath.IsLocal(rel) {
		return formalModule{reason: fmt.Sprintf("module %s resolves outside the model root", file)}
	}
	data, err := readCappedFile(real, maxFormalModuleBytes)
	switch {
	case errors.Is(err, errNotRegular):
		return formalModule{reason: fmt.Sprintf("module %s is not a regular file", file)}
	case errors.Is(err, errTooLarge):
		return formalModule{reason: fmt.Sprintf("module %s is larger than %d MiB", file, maxFormalModuleBytes>>20)}
	case err != nil:
		return formalModule{reason: fmt.Sprintf("module %s is unreadable", file)}
	}
	data = bytes.ReplaceAll(data, []byte("\r\n"), []byte("\n"))
	sum := sha256.Sum256(data)
	header, _, _ := bytes.Cut(data, []byte("\n"))
	return formalModule{sha: hex.EncodeToString(sum[:]), header: string(header)}
}

var (
	errNotRegular = errors.New("not a regular file")
	errTooLarge   = errors.New("file too large")
)

// readCappedFile reads a regular file of at most limit bytes. It never blocks
// on or drains a special file: the file is opened without waiting where the
// platform allows, checked to be regular after opening and read through a
// limit reader.
//
// ENGMODEL-LINKS: FU-CODEMAP-INFERENCE
// TRLC-LINKS: REQ-EMG-145
func readCappedFile(path string, limit int64) ([]byte, error) {
	if info, err := os.Stat(path); err == nil && !info.Mode().IsRegular() {
		return nil, errNotRegular
	}
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, errNotRegular
	}
	data, err := io.ReadAll(io.LimitReader(f, limit+1))
	if err != nil {
		return nil, err
	}
	if int64(len(data)) > limit {
		return nil, errTooLarge
	}
	return data, nil
}

// ErrHandWritten is returned when a work file exists without the engws header.
var ErrHandWritten = errors.New("not generated by engws")

// SyncResult names the files sync wrote or removed.
type SyncResult struct {
	WorkFile      string
	GoWork        string // written go.work, empty when none
	GoWorkRemoved bool
}

// Sync writes root/engmod.work.yml with every local checkout and root/go.work
// with every checkout that has go.mod, removing go.work when none do. A
// non-local checkout is at its published tag, so its code equals the version
// a consumer pins at that tag; another pinned version is reported by Skews.
// Listing every Go checkout lets go test and go run work in each of them.
// It writes nothing inside a checkout. A work file that engws did not
// generate is kept unless force is set.
// TRLC-LINKS: REQ-EMG-068
// ENGMODEL-LINKS: FU-CLI-ORCHESTRATION, FU-SYSTEM-COMPOSITION
func Sync(plan Plan, goVersion string, force bool) (SyncResult, error) {
	workPath := filepath.Join(plan.Root, model.WorkspaceFileName)
	goWorkPath := filepath.Join(plan.Root, GoWorkFileName)
	for _, path := range []string{workPath, goWorkPath} {
		if err := checkOwned(path, force); err != nil {
			return SyncResult{}, err
		}
	}
	local := plan.Local()
	if err := writeFileAtomic(workPath, []byte(renderWorkFile(local))); err != nil {
		return SyncResult{}, err
	}
	result := SyncResult{WorkFile: workPath}
	var goDirs []string
	for _, entry := range plan.Entries {
		if entry.GoModule != "" {
			goDirs = append(goDirs, entry.Name)
		}
	}
	if len(goDirs) == 0 {
		if err := os.Remove(goWorkPath); err == nil {
			result.GoWorkRemoved = true
		} else if !errors.Is(err, os.ErrNotExist) {
			return result, err
		}
		return result, nil
	}
	if err := writeFileAtomic(goWorkPath, []byte(renderGoWork(goVersion, goDirs))); err != nil {
		return result, err
	}
	result.GoWork = goWorkPath
	return result, nil
}

// checkOwned refuses to replace an existing file that lacks the engws header.
// TRLC-LINKS: REQ-EMG-068
func checkOwned(path string, force bool) error {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) || force {
		return nil
	}
	if err != nil {
		return err
	}
	if !strings.Contains(firstLine(string(data)), generatedHeader) {
		return fmt.Errorf("%s: %w; move it away or use --force", path, ErrHandWritten)
	}
	return nil
}

// firstLine returns the first line of text.
// TRLC-LINKS: REQ-EMG-068
func firstLine(text string) string {
	line, _, _ := strings.Cut(text, "\n")
	return line
}

// renderWorkFile renders engmod.work.yml with one replacement per checkout.
// TRLC-LINKS: REQ-EMG-068
func renderWorkFile(local []Entry) string {
	var b strings.Builder
	b.WriteString("# " + generatedHeader + "\nschemaVersion: 2\n")
	if len(local) == 0 {
		b.WriteString("replacements: []\n")
		return b.String()
	}
	b.WriteString("replacements:\n")
	for _, entry := range local {
		fmt.Fprintf(&b, "  - module: %s\n    path: ./%s\n", entry.Manifest.Module.Path, entry.Name)
	}
	return b.String()
}

// renderGoWork renders go.work using each listed directory.
// TRLC-LINKS: REQ-EMG-068
func renderGoWork(goVersion string, dirs []string) string {
	var b strings.Builder
	b.WriteString("// " + generatedHeader + "\n\ngo " + goVersion + "\n\nuse (\n")
	for _, dir := range dirs {
		b.WriteString("\t./" + dir + "\n")
	}
	b.WriteString(")\n")
	return b.String()
}

var goVersionPattern = regexp.MustCompile(`^go(1\.\d+(?:\.\d+)?)`)

// GoVersion returns the local toolchain as the go.work go directive value
// (go1.27.3 -> 1.27.3; pre-release suffixes dropped).
// TRLC-LINKS: REQ-EMG-068
func GoVersion() (string, error) {
	out, err := exec.Command("go", "env", "GOVERSION").Output()
	if err != nil {
		return "", fmt.Errorf("go env GOVERSION: %w", err)
	}
	return parseGoVersion(strings.TrimSpace(string(out)))
}

// parseGoVersion strips "go" and any suffix after the numeric version.
// TRLC-LINKS: REQ-EMG-068
func parseGoVersion(v string) (string, error) {
	m := goVersionPattern.FindStringSubmatch(v)
	if m == nil {
		return "", fmt.Errorf("unrecognised go version %q", v)
	}
	return m[1], nil
}

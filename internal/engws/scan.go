// Package engws is the multi-repository workspace helper behind cmd/engws.
// It scans the model checkouts under a workspace root, decides which ones
// must resolve locally, and writes the root-level engmod.work.yml and go.work.
package engws

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	cuemodule "cuelang.org/go/mod/module"
	"github.com/labeth/engineering-model-go/model"
	"golang.org/x/mod/modfile"
	"gopkg.in/yaml.v3"
)

const (
	// StateFileName holds the workspace pins; it lives at the root only.
	StateFileName = ".engws.yml"
	// GoWorkFileName is the Go workspace written next to engmod.work.yml.
	GoWorkFileName = "go.work"
	// generatedHeader marks files engws owns and may overwrite.
	generatedHeader = "generated by engws, local-only; do not commit"
)

// Checkout is one direct child directory of the root holding an engmod.yml.
type Checkout struct {
	Name     string // directory name under the root
	Dir      string // absolute directory
	Manifest model.ManifestDocument
	GoModule string // module path from go.mod, empty without go.mod
	// GoRequires maps each module path required in go.mod to its version.
	GoRequires map[string]string
}

// FindRoot returns the nearest directory at or above start that contains
// engmod.work.yml or .engws.yml, or start itself when none does. The search
// stops below $HOME: $HOME and its ancestors are never returned, so a stray
// marker there cannot make sync write $HOME/go.work. A world-writable root
// is refused; give it explicitly with --root.
// TRLC-LINKS: REQ-EMG-068
// ENGMODEL-LINKS: FU-CLI-ORCHESTRATION, FU-SYSTEM-COMPOSITION
func FindRoot(start string) (string, error) {
	abs, err := filepath.Abs(start)
	if err != nil {
		return "", err
	}
	root := abs
	for dir := abs; !isHomeOrAncestor(dir); {
		if hasRootMarker(dir) {
			root = dir
			break
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	if info, err := os.Stat(root); err == nil && info.Mode().Perm()&0o002 != 0 {
		return "", fmt.Errorf("workspace root %s is world-writable; pass it with --root if you trust it", root)
	}
	return root, nil
}

// hasRootMarker reports whether dir holds engmod.work.yml or .engws.yml.
// TRLC-LINKS: REQ-EMG-068
func hasRootMarker(dir string) bool {
	for _, name := range []string{model.WorkspaceFileName, StateFileName} {
		if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
			return true
		}
	}
	return false
}

// isHomeOrAncestor reports whether dir is $HOME or one of its ancestors.
// TRLC-LINKS: REQ-EMG-068
func isHomeOrAncestor(dir string) bool {
	home, err := os.UserHomeDir()
	if err != nil || strings.TrimSpace(home) == "" {
		return false
	}
	if abs, err := filepath.Abs(home); err == nil {
		home = abs
	}
	// Compare given and symlink-resolved forms, so a symlinked home (or a
	// project reached through its real path) still stops the search.
	homes := []string{home}
	if real, err := filepath.EvalSymlinks(home); err == nil && real != home {
		homes = append(homes, real)
	}
	dirs := []string{dir}
	if real, err := filepath.EvalSymlinks(dir); err == nil && real != dir {
		dirs = append(dirs, real)
	}
	for _, h := range homes {
		for _, d := range dirs {
			rel, err := filepath.Rel(d, h)
			if err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) && !filepath.IsAbs(rel) {
				return true
			}
		}
	}
	return false
}

// Scan lists the direct children of root that hold an engmod.yml, sorted by
// name. Dot directories are skipped. A manifest that cannot be read is an
// error naming the checkout, since every later decision depends on it.
// TRLC-LINKS: REQ-EMG-068
// ENGMODEL-LINKS: FU-CLI-ORCHESTRATION, FU-SYSTEM-COMPOSITION
func Scan(root string) ([]Checkout, error) {
	checkouts, _, err := ScanWithWarnings(root)
	return checkouts, err
}

// safeDirName is the directory name a checkout may have: engws writes it
// unquoted into engmod.work.yml and go.work.
var safeDirName = regexp.MustCompile(`^[A-Za-z0-9._-]+$`)

// ScanWithWarnings is Scan that also returns one warning per skipped
// checkout: a directory name outside [A-Za-z0-9._-] or a module.path that is
// not a valid CUE module path (host/path@vN). Neither is written into the
// work files.
// TRLC-LINKS: REQ-EMG-068
// ENGMODEL-LINKS: FU-CLI-ORCHESTRATION
func ScanWithWarnings(root string) ([]Checkout, []string, error) {
	entries, err := os.ReadDir(root)
	if err != nil {
		return nil, nil, err
	}
	var out []Checkout
	var warnings []string
	var errs []error
	for _, entry := range entries {
		name := entry.Name()
		if strings.HasPrefix(name, ".") {
			continue
		}
		dir := filepath.Join(root, name)
		if info, err := os.Stat(dir); err != nil || !info.IsDir() {
			continue
		}
		manifestPath := filepath.Join(dir, "engmod.yml")
		if _, err := os.Stat(manifestPath); err != nil {
			continue
		}
		if !safeDirName.MatchString(name) {
			warnings = append(warnings, fmt.Sprintf("skipping %q: directory name must match %s", name, safeDirName))
			continue
		}
		manifest, err := readManifest(manifestPath)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", name, err))
			continue
		}
		if err := cuemodule.CheckPath(manifest.Module.Path); err != nil || !strings.Contains(manifest.Module.Path, "@v") {
			warnings = append(warnings, fmt.Sprintf("%s: module.path %q is not a valid major-qualified module path; skipped", name, manifest.Module.Path))
			continue
		}
		goModule, goRequires, err := readGoModule(dir)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", name, err))
			continue
		}
		out = append(out, Checkout{Name: name, Dir: dir, Manifest: manifest, GoModule: goModule, GoRequires: goRequires})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, warnings, errors.Join(errs...)
}

// readManifest decodes only the manifest into the library's manifest type;
// the domain documents are not needed to plan a workspace.
// TRLC-LINKS: REQ-EMG-068
func readManifest(path string) (model.ManifestDocument, error) {
	var manifest model.ManifestDocument
	data, err := os.ReadFile(path)
	if err != nil {
		return manifest, err
	}
	if err := yaml.NewDecoder(bytes.NewReader(data)).Decode(&manifest); err != nil {
		return manifest, fmt.Errorf("decode %s: %w", path, err)
	}
	if strings.TrimSpace(manifest.Module.Path) == "" {
		return manifest, fmt.Errorf("%s: module.path is empty", path)
	}
	if strings.TrimSpace(manifest.Module.Version) == "" {
		return manifest, fmt.Errorf("%s: module.version is empty", path)
	}
	return manifest, nil
}

// readGoModule returns the module path declared in dir/go.mod and its
// requires (path to version), or "" and nil without go.mod.
// TRLC-LINKS: REQ-EMG-068
func readGoModule(dir string) (string, map[string]string, error) {
	data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if errors.Is(err, os.ErrNotExist) {
		return "", nil, nil
	}
	if err != nil {
		return "", nil, err
	}
	file, err := modfile.ParseLax("go.mod", data, nil)
	if err != nil {
		return "", nil, fmt.Errorf("go.mod: %w", err)
	}
	if file.Module == nil || file.Module.Mod.Path == "" {
		return "", nil, fmt.Errorf("go.mod has no module directive")
	}
	requires := map[string]string{}
	for _, r := range file.Require {
		requires[r.Mod.Path] = r.Mod.Version
	}
	return file.Module.Mod.Path, requires, nil
}

// tagFor is the git tag that releases a manifest version: v<version>, with
// or without a leading v in the manifest.
// TRLC-LINKS: REQ-EMG-068
func tagFor(version string) string {
	return "v" + strings.TrimPrefix(strings.TrimSpace(version), "v")
}

// state is the content of .engws.yml.
type state struct {
	Pins []string `yaml:"pins"`
}

// LoadPins reads the pinned checkout names from root/.engws.yml.
// TRLC-LINKS: REQ-EMG-068
// ENGMODEL-LINKS: FU-CLI-ORCHESTRATION
func LoadPins(root string) (map[string]bool, error) {
	pins := map[string]bool{}
	data, err := os.ReadFile(filepath.Join(root, StateFileName))
	if errors.Is(err, os.ErrNotExist) {
		return pins, nil
	}
	if err != nil {
		return nil, err
	}
	var s state
	if err := yaml.Unmarshal(data, &s); err != nil {
		return nil, fmt.Errorf("decode %s: %w", StateFileName, err)
	}
	for _, pin := range s.Pins {
		if pin = strings.TrimSpace(pin); pin != "" {
			pins[pin] = true
		}
	}
	return pins, nil
}

// SavePins writes root/.engws.yml with the pins sorted.
// TRLC-LINKS: REQ-EMG-068
// ENGMODEL-LINKS: FU-CLI-ORCHESTRATION
func SavePins(root string, pins map[string]bool) error {
	names := make([]string, 0, len(pins))
	for name := range pins {
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("# engws: checkouts always resolved locally; local-only, do not commit\n")
	if len(names) == 0 {
		b.WriteString("pins: []\n")
	} else {
		b.WriteString("pins:\n")
		for _, name := range names {
			fmt.Fprintf(&b, "  - %s\n", name)
		}
	}
	return writeFileAtomic(filepath.Join(root, StateFileName), []byte(b.String()))
}

// writeFileAtomic writes through a temporary file in the same directory.
// TRLC-LINKS: REQ-EMG-068
func writeFileAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	name := tmp.Name()
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		os.Remove(name)
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(name)
		return err
	}
	if err := os.Chmod(name, 0o644); err != nil {
		os.Remove(name)
		return err
	}
	if err := os.Rename(name, path); err != nil {
		os.Remove(name)
		return err
	}
	return nil
}

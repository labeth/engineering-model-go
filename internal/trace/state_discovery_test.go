// phaseSource is a package whose type Phase has three constants, a field of
// the type and an assignment to the field: the minimal candidate. The type is
// declared on line 2.
const phaseSource = "package p\ntype Phase int\nconst (\n\tA Phase = iota\n\tB\n\tC\n)\ntype H struct{ phase Phase }\nfunc set(h *H) { h.phase = B }\n"

// writeGoFiles writes the files into a new directory and returns the code
// items the scan makes of them: one source file item each.
func writeGoFiles(t *testing.T, files map[string]string) []codescan.CodeItem {
	t.Helper()
	root := t.TempDir()
	var items []codescan.CodeItem
	for name, text := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
		items = append(items, codescan.CodeItem{Kind: "source_file", Owner: "FU-A", Source: name, Element: name, AbsPath: path})
	}
	return items
}

// withLinks adds a symbol item at the given line of the first item's file.
func withLinks(items []codescan.CodeItem, line string, ids ...string) []codescan.CodeItem {
	sym := codescan.CodeItem{Kind: "symbol", Source: items[0].Source + ":" + line, AbsPath: items[0].AbsPath, ModelLinks: ids}
	return append(items, sym)
}

// discoveryReported returns the sorted "code path" of the diagnostics.
func discoveryReported(diags []validate.Diagnostic) []string {
	return reported(diags)
}

const (
	candidateAt2 = "code.state_candidate_unlinked a.go:2"
	unreasonedAt = "code.state_suppression_unreasoned a.go:2"
	unusedAt2    = "code.state_suppression_unused a.go:2"
)

// The discovery reports a Go type that has three constants, a field of the
// type and an assignment to a field of that name, and nothing that lacks any
// of the three, that is named like a kind or option, that sits in a test or
// generated file or in another package.
// Mutation: lowering GoStateMinConstants to 2, dropping the assignment test
// in packageFacts.candidate, dropping a name from goStateExcludedSuffixes, or
// letting goStateSource accept test files, changes a row.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestStateDiscoveryCandidateRule(t *testing.T) {
	rename := func(name string) string { return strings.ReplaceAll(phaseSource, "Phase", name) }
	cases := []struct {
		name  string
		files map[string]string
		want  []string
	}{
		{"three constants, field and assignment", map[string]string{"a.go": phaseSource}, []string{candidateAt2}},
		{"a State type", map[string]string{"a.go": rename("State")}, []string{candidateAt2}},
		{"suffix Kind", map[string]string{"a.go": rename("PhaseKind")}, nil},
		{"suffix Severity", map[string]string{"a.go": rename("Severity")}, nil},
		{"suffix Format", map[string]string{"a.go": rename("ExportFormat")}, nil},
		{"suffix Type", map[string]string{"a.go": rename("MachineType")}, nil},
		{"suffix Reason", map[string]string{"a.go": rename("Reason")}, nil},
		{"suffix Mode", map[string]string{"a.go": rename("RunMode")}, nil},
		{"suffix Option", map[string]string{"a.go": rename("FlagOption")}, nil},
		{"the suffix is case sensitive", map[string]string{"a.go": rename("Phasekind")}, []string{candidateAt2}},
		{"two constants", map[string]string{"a.go": strings.Replace(phaseSource, "\tC\n", "", 1)}, nil},
		{"no field of the type", map[string]string{"a.go": strings.Replace(phaseSource, "phase Phase", "phase int", 1)}, nil},
		{"no assignment", map[string]string{"a.go": strings.Replace(phaseSource, "h.phase = B", "_ = h.phase", 1)}, nil},
		{"a composite literal is no assignment", map[string]string{"a.go": strings.Replace(phaseSource, "h.phase = B", "_ = H{phase: B}", 1)}, nil},
		{"a plain variable is no field assignment", map[string]string{"a.go": strings.Replace(phaseSource, "h.phase = B", "var p Phase; p = B; _ = p", 1)}, nil},
		{"a test file", map[string]string{"a_test.go": phaseSource}, nil},
		{"a generated file", map[string]string{"a.go": "// Code generated by tool. DO NOT EDIT.\n" + phaseSource}, nil},
		{"a non-Go file", map[string]string{"a.rs": phaseSource}, nil},
		{"a field of another type does not count", map[string]string{"a.go": strings.Replace(phaseSource, "phase Phase", "phase Phases", 1)}, nil},
		{"constants, field and assignment in three files of one package", map[string]string{
			"a.go": "package p\ntype Phase int\n",
			"b.go": "package p\nconst (\n\tA Phase = iota\n\tB\n\tC\n)\n",
			"c.go": "package p\ntype H struct{ phase Phase }\nfunc set(h *H) { h.phase = B }\n",
		}, []string{candidateAt2}},
		{"the same facts in two directories are no package", map[string]string{
			"a/a.go": "package p\ntype Phase int\nconst (\n\tA Phase = iota\n\tB\n\tC\n)\n",
			"b/b.go": "package p\ntype H struct{ phase Phase }\nfunc set(h *H) { h.phase = 1 }\n",
		}, nil},
		{"a conversion constants block", map[string]string{"a.go": "package p\ntype Phase string\nconst A = Phase(\"a\")\nconst B = Phase(\"b\")\nconst C = Phase(\"c\")\ntype H struct{ phase Phase }\nfunc set(h *H) { h.phase = B }\n"}, []string{candidateAt2}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := discoveryReported(stateDiscoveryDiagnostics(coverageBundle(), writeGoFiles(t, c.files)))
			if len(got) == 0 {
				got = nil
			}
			if !reflect.DeepEqual(got, c.want) {
				t.Fatalf("reported %v, want %v", got, c.want)
			}
		})
	}
}

// A model link marker that names a machine, a state or a transition of the
// model clears the candidate; one that names anything else does not.
// Mutation: accepting any marker (dropping the d.modeled test in linked), or
// reading the link from the wrong line, changes a row.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestStateDiscoveryModelLinkClears(t *testing.T) {
	cases := []struct {
		name string
		ids  []string
		want []string
	}{
		{"a machine", []string{"SM-A"}, nil},
		{"a state", []string{"STATE-1"}, nil},
		{"a transition", []string{"TR-2"}, nil},
		{"a machine among others", []string{"FU-A", "SM-A"}, nil},
		{"a machine that is not in the model", []string{"SM-GHOST"}, []string{candidateAt2}},
		{"a functional unit", []string{"FU-A"}, []string{candidateAt2}},
		{"an interface", []string{"IF-A"}, []string{candidateAt2}},
		{"no marker names anything", nil, []string{candidateAt2}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			items := withLinks(writeGoFiles(t, map[string]string{"a.go": phaseSource}), "2", c.ids...)
			got := discoveryReported(stateDiscoveryDiagnostics(coverageBundle(), items))
			if len(got) == 0 {
				got = nil
			}
			if !reflect.DeepEqual(got, c.want) {
				t.Fatalf("reported %v, want %v", got, c.want)
			}
		})
	}
	t.Run("a marker on another line", func(t *testing.T) {
		items := withLinks(writeGoFiles(t, map[string]string{"a.go": phaseSource}), "8", "SM-A")
		if got := discoveryReported(stateDiscoveryDiagnostics(coverageBundle(), items)); !reflect.DeepEqual(got, []string{candidateAt2}) {
			t.Fatalf("reported %v", got)
		}
	})
}

// suppressed is phaseSource with the lines inserted before the type
// declaration (so the type is on line 2 plus the number of lines).
func suppressed(lines ...string) string {
	return strings.Replace(phaseSource, "type Phase int", strings.Join(append(lines, "type Phase int"), "\n"), 1)
}

const notAStateReason = "// ENGMODEL-NOT-A-STATE: the phases are display colours of a legend, not a lifecycle"

// A comment ENGMODEL-NOT-A-STATE with a reason of at least 20 characters that
// is not a placeholder, on the declaration line or within three lines above
// it, clears the candidate. A reason that is missing, short or a placeholder
// is code.state_suppression_unreasoned (an error) and clears nothing.
// Mutation: widening the window of attachedType to four lines, dropping the
// placeholder test of reasonProblem, or the length test, changes a row.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestStateDiscoverySuppression(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want []string
	}{
		{"a good reason on the line above", suppressed(notAStateReason), nil},
		{"a good reason on the declaration line", strings.Replace(phaseSource, "type Phase int", "type Phase int "+notAStateReason, 1), nil},
		{"a good reason three lines above", suppressed(notAStateReason, "", ""), nil},
		{"a good reason four lines above", suppressed(notAStateReason, "", "", ""), []string{
			"code.state_suppression_unused a.go:2", "code.state_candidate_unlinked a.go:6"}},
		{"a reason that contains placeholder words", suppressed("// ENGMODEL-NOT-A-STATE: ignore the later phases, they are colours"), nil},
		{"a reason of exactly 20 characters", suppressed("// ENGMODEL-NOT-A-STATE: 12345678901234567890"), nil},
		{"a reason of 19 characters", suppressed("// ENGMODEL-NOT-A-STATE: 1234567890123456789"), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"a short reason", suppressed("// ENGMODEL-NOT-A-STATE: colours"), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"no reason", suppressed("// ENGMODEL-NOT-A-STATE"), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"an empty reason after the colon", suppressed("// ENGMODEL-NOT-A-STATE:   "), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"placeholder todo", suppressed("// ENGMODEL-NOT-A-STATE: TODO"), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"placeholder tbd repeated to 20 characters", suppressed("// ENGMODEL-NOT-A-STATE: tbd tbd tbd tbd tbd tbd tbd"), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"placeholder n/a", suppressed("// ENGMODEL-NOT-A-STATE: N/A"), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"placeholder not a state", suppressed("// ENGMODEL-NOT-A-STATE: not a state, not a state."), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"placeholders mixed", suppressed("// ENGMODEL-NOT-A-STATE: fixme xxx later wip none ignore"), []string{unreasonedAt, "code.state_candidate_unlinked a.go:3"}},
		{"a mention in a sentence is no suppression", suppressed("// a comment about ENGMODEL-NOT-A-STATE: and nothing else here"), []string{"code.state_candidate_unlinked a.go:3"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := discoveryReported(stateDiscoveryDiagnostics(coverageBundle(), writeGoFiles(t, map[string]string{"a.go": c.src})))
			if len(got) == 0 {
				got = nil
			}
			sort.Strings(c.want)
			if !reflect.DeepEqual(got, c.want) {
				t.Fatalf("reported %v, want %v", got, c.want)
			}
		})
	}
}

// A suppression on a declaration that is not a candidate, or that is linked to
// a machine, is code.state_suppression_unused; one that is not on a type at
// all is too.
// Mutation: treating a linked candidate as cleared by the suppression (dropping
// the d.linked test of clearedLine) drops the second row.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestStateDiscoveryUnusedSuppression(t *testing.T) {
	two := strings.Replace(suppressed(notAStateReason), "\tC\n", "", 1)
	kind := strings.ReplaceAll(suppressed(notAStateReason), "Phase", "PhaseKind")
	noType := "package p\n" + notAStateReason + "\nvar x int\n"
	cases := []struct {
		name  string
		src   string
		links []string
		want  []string
	}{
		{"a type with two constants", two, nil, []string{unusedAt2}},
		{"a type excluded by its name", kind, nil, []string{unusedAt2}},
		{"a linked candidate", suppressed(notAStateReason), []string{"SM-A"}, []string{unusedAt2}},
		{"a candidate linked to something that is no machine", suppressed(notAStateReason), []string{"FU-A"}, nil},
		{"a comment above no type", noType, nil, []string{"code.state_suppression_unused a.go:2"}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			items := writeGoFiles(t, map[string]string{"a.go": c.src})
			if c.links != nil {
				items = withLinks(items, "3", c.links...)
			}
			got := discoveryReported(stateDiscoveryDiagnostics(coverageBundle(), items))
			if len(got) == 0 {
				got = nil
			}
			if !reflect.DeepEqual(got, c.want) {
				t.Fatalf("reported %v, want %v", got, c.want)
			}
		})
	}
}

// The diagnostics carry their severity and a remedy: a warning for the
// candidate and the unused suppression, an error for the unreasoned one. The
// candidate remedy names both ways to clear it.
// Mutation: emitting the unreasoned suppression as a warning, or dropping the
// remedy of the candidate, fails.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestStateDiscoverySeverityAndRemedy(t *testing.T) {
	two := strings.Replace(suppressed(notAStateReason), "\tC\n", "", 1)
	for _, c := range []severityCase{
		{"candidate", phaseSource, codeStateCandidate, validate.SeverityWarning, []string{"ef-behavior", "ef-code-linking", "ENGMODEL-NOT-A-STATE", "at least 20 characters"}},
		{"unreasoned", suppressed("// ENGMODEL-NOT-A-STATE: todo"), codeStateUnreasoned, validate.SeverityError, []string{"ENGMODEL-NOT-A-STATE", "20 characters"}},
		{"unused", two, codeStateUnused, validate.SeverityWarning, []string{"remove the ENGMODEL-NOT-A-STATE"}},
	} {
		t.Run(c.name, func(t *testing.T) { assertSeverityAndRemedy(t, c) })
	}
	t.Run("the message names the type, constants and field", func(t *testing.T) { assertCandidateMessage(t) })
}

// severityCase is one source and the single diagnostic of a code it must give.
type severityCase struct {
	name     string
	src      string
	code     string
	severity validate.Severity
	contains []string
}

// diagnosticsOfCode returns the discovery diagnostics of one code for a source.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func diagnosticsOfCode(t *testing.T, src, code string) []validate.Diagnostic {
	t.Helper()
	var found []validate.Diagnostic
	for _, d := range stateDiscoveryDiagnostics(coverageBundle(), writeGoFiles(t, map[string]string{"a.go": src})) {
		if d.Code == code {
			found = append(found, d)
		}
	}
	return found
}

// assertSeverityAndRemedy checks the one diagnostic, its severity and its remedy text.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func assertSeverityAndRemedy(t *testing.T, c severityCase) {
	t.Helper()
	found := diagnosticsOfCode(t, c.src, c.code)
	if len(found) != 1 || found[0].Severity != c.severity {
		t.Fatalf("want one %s of severity %s, got %+v", c.code, c.severity, found)
	}
	for _, want := range c.contains {
		if !strings.Contains(found[0].Remedy, want) {
			t.Errorf("remedy %q lacks %q", found[0].Remedy, want)
		}
	}
}

// assertCandidateMessage checks that the message names the type, constants and field.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func assertCandidateMessage(t *testing.T) {
	t.Helper()
	d := stateDiscoveryDiagnostics(coverageBundle(), writeGoFiles(t, map[string]string{"a.go": phaseSource}))
	if len(d) != 1 {
		t.Fatalf("want one diagnostic, got %+v", d)
	}
	for _, want := range []string{"Phase", "3 constants", "field phase"} {
		if !strings.Contains(d[0].Message, want) {
			t.Errorf("message %q lacks %q", d[0].Message, want)
		}
	}
}

// The discovery is part of the integrity check, runs on the scanned code of a
// model without any machine, and leaves out the directories that
// inferenceHints.exclude names, because it reads the same code items.
// Mutation: removing the stateDiscoveryDiagnostics call from integrityTail
// drops the code; scanning the excluded directory reports its type too.
// TRLC-LINKS: REQ-EMG-188
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE, FU-CODEMAP-INFERENCE
func TestValidateIntegrityReportsStateCandidates(t *testing.T) {
	root := t.TempDir()
	linked := strings.Replace(phaseSource, "func set", "// TRLC-LINKS: REQ-EMG-188\nfunc set", 1)
	for name, text := range map[string]string{
		"live/a.go": "// ENGMODEL-OWNER-UNIT: FU-A\n" + linked,
		"skip/b.go": "// ENGMODEL-OWNER-UNIT: FU-A\n" + linked,
	} {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(text), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	bundle := model.Bundle{ArchitecturePath: filepath.Join(root, "engmod.yml")}
	bundle.Architecture.InferenceHints.Exclude = []string{"skip/**"}
	code, diags := codescan.InferCodeItems(bundle, "")
	if len(diags) != 0 {
		t.Fatalf("code inference: %+v", diags)
	}
	got := pathsOf(ValidateIntegrity(bundle, model.RequirementsDocument{}, code, nil), codeStateCandidate)
	if want := []string{"live/a.go:3"}; !reflect.DeepEqual(got, want) {
		t.Fatalf("%s at %v, want %v", codeStateCandidate, got, want)
	}
}

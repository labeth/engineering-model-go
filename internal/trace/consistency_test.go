// pathsOf returns the sorted paths of the diagnostics with a code.
func pathsOf(diags []validate.Diagnostic, code string) []string {
	out := []string{}
	for _, d := range diags {
		if d.Code == code {
			out = append(out, d.Path)
		}
	}
	sort.Strings(out)
	return out
}

// A source file whose ENGMODEL-OWNER-UNIT marker is missing or names no
// functional unit is reported once; a file naming a unit, a test file, a
// generated file and an imported alias::ID owner are not.
// Mutation: dropping the unit lookup, the generated-file exemption or the
// test-file exemption in ownerProblem changes the reported set.
// TRLC-LINKS: REQ-EMG-170
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestOwnerDiagnostics(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"owned.go":        "// ENGMODEL-OWNER-UNIT: FU-A\npackage p\n",
		"missing.go":      "package p\n",
		"ghost.go":        "// ENGMODEL-OWNER-UNIT: FU-GHOST\npackage p\n",
		"requirement.go":  "// ENGMODEL-OWNER-UNIT: REQ-A\npackage p\n",
		"alias.go":        "// ENGMODEL-OWNER-UNIT: dep::FU-X\npackage p\n",
		"missing_test.go": "package p\n",
		"gen.go":          "// Code generated by tool; DO NOT EDIT.\npackage p\n",
		"sub/also.go":     "// ENGMODEL-OWNER-UNIT: FU-A\npackage q\n",
	}
	for name, content := range files {
		testutil.WriteFile(t, filepath.Join(root, filepath.FromSlash(name)), content)
	}
	bundle := model.Bundle{ArchitecturePath: filepath.Join(root, "engmod.yml")}
	bundle.Architecture.AuthoredArchitecture.FunctionalUnits = []model.FunctionalUnit{{ID: "FU-A"}}
	items, _ := codescan.InferCodeItems(bundle, root)

	diags := ownerDiagnostics(bundle, items)
	want := []string{"ghost.go", "missing.go", "requirement.go"}
	if got := pathsOf(diags, "code.owner_unresolved"); !reflect.DeepEqual(got, want) {
		t.Fatalf("code.owner_unresolved at %v, want %v", got, want)
	}
	for _, d := range diags {
		if d.Severity != validate.SeverityWarning || d.Remedy == "" {
			t.Fatalf("want a warning with a remedy: %+v", d)
		}
	}
}

// ownerProblem judges one item: only a source file is judged, and the message
// says whether the marker is missing or names no unit.
// Mutation: treating a symbol item like a source file reports the first case.
// TRLC-LINKS: REQ-EMG-170
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestOwnerProblemCases(t *testing.T) {
	units := map[string]bool{"FU-A": true}
	cases := []struct {
		name    string
		item    codescan.CodeItem
		problem string
	}{
		{"symbol is not judged", codescan.CodeItem{Kind: "symbol", Owner: "unresolved", Source: "a.go:3"}, ""},
		{"known unit", codescan.CodeItem{Kind: "source_file", Owner: " FU-A ", Source: "a.go"}, ""},
		{"imported unit", codescan.CodeItem{Kind: "source_file", Owner: "dep::FU-Z", Source: "a.go"}, ""},
		{"unresolved", codescan.CodeItem{Kind: "source_file", Owner: "unresolved", Source: "a.go"}, "file a.go has no ENGMODEL-OWNER-UNIT marker naming the functional unit that owns it"},
		{"empty", codescan.CodeItem{Kind: "source_file", Source: "a.go"}, "file a.go has no ENGMODEL-OWNER-UNIT marker naming the functional unit that owns it"},
		{"unknown unit", codescan.CodeItem{Kind: "source_file", Owner: "FU-B", Source: "a.go"}, `ENGMODEL-OWNER-UNIT "FU-B" of file a.go is not a functional unit of the model`},
	}
	for _, c := range cases {
		if got := ownerProblem(c.item, units); got != c.problem {
			t.Errorf("%s: got %q, want %q", c.name, got, c.problem)
		}
	}
}

// kindsBundle is a model with unit FU-A, a requirement REQ-A, a catalog term
// TERM-A and a catalog entry FU-A that an authored element shares its ID with.
func kindsBundle() (model.Bundle, model.RequirementsDocument) {
	bundle := model.Bundle{}
	bundle.Architecture.AuthoredArchitecture.FunctionalUnits = []model.FunctionalUnit{{ID: "FU-A"}}
	bundle.Catalog.Catalog.Actors = []model.CatalogEntry{{ID: "TERM-A"}}
	bundle.Catalog.Catalog.FunctionalUnits = []model.CatalogEntry{{ID: "FU-A"}}
	reqs := model.RequirementsDocument{Requirements: []model.Requirement{{ID: "REQ-A"}}}
	bundle.Requirements = reqs
	return bundle, reqs
}

// knownModelKinds names the same IDs as KnownModelIDs and gives an element
// that is also a catalog entry the kind element.
// Mutation: letting the catalog or requirement kind overwrite the element
// kind makes FU-A a catalog term.
// TRLC-LINKS: REQ-EMG-028
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestKnownModelKinds(t *testing.T) {
	bundle, reqs := kindsBundle()
	kinds := knownModelKinds(bundle, reqs)
	want := map[string]string{"FU-A": kindElement, "REQ-A": kindRequirement, "TERM-A": kindTerm}
	if !reflect.DeepEqual(kinds, want) {
		t.Fatalf("kinds %v, want %v", kinds, want)
	}
	ids := KnownModelIDs(bundle, reqs)
	if len(ids) != len(kinds) {
		t.Fatalf("KnownModelIDs %v and knownModelKinds %v differ", ids, kinds)
	}
	for id := range ids {
		if kinds[id] == "" {
			t.Errorf("%s has no kind", id)
		}
	}
}

// An ENGMODEL-LINKS target that is a requirement or a catalog term is a
// mismatch; an element, a missing ID (code.dangling_model_link) and an
// imported alias::ID are not.
// Mutation: reporting every kind other than element, or only requirements,
// changes the reported set.
// TRLC-LINKS: REQ-EMG-171
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestModelLinkKindDiagnostics(t *testing.T) {
	bundle, _ := kindsBundle()
	cases := []struct {
		name  string
		links []string
		want  int
	}{
		{"element", []string{"FU-A"}, 0},
		{"requirement", []string{"REQ-A"}, 1},
		{"catalog term", []string{"TERM-A"}, 1},
		{"missing id", []string{"FU-GHOST"}, 0},
		{"imported", []string{"dep::FU-X"}, 0},
		{"mixed", []string{"FU-A", "REQ-A", "TERM-A", "FU-GHOST"}, 2},
	}
	for _, c := range cases {
		diags := modelLinkKindDiagnostics(bundle, []codescan.CodeItem{{Kind: "symbol", Source: "a.go:3", ModelLinks: c.links}})
		if len(diags) != c.want {
			t.Errorf("%s: %d diagnostics, want %d: %+v", c.name, len(diags), c.want, diags)
		}
		requireShape(t, diags, "code.model_link_kind_mismatch")
		if got := pathsOf(diags, "code.model_link_kind_mismatch"); len(got) != c.want || (c.want > 0 && got[0] != "a.go:3") {
			t.Errorf("%s: paths %v", c.name, got)
		}
	}
}

// requireShape fails when a diagnostic has another code, no remedy or is not
// a warning.
func requireShape(t *testing.T, diags []validate.Diagnostic, code string) {
	t.Helper()
	for _, d := range diags {
		if d.Code != code || d.Remedy == "" || d.Severity != validate.SeverityWarning {
			t.Errorf("%+v", d)
		}
	}
}

// machineFixture builds a model with machines and a temp directory holding
// the files, and returns the machine diagnostics at the tier-less severity.
func machineFixture(t *testing.T, machines []model.Machine, files map[string]string) []validate.Diagnostic {
	t.Helper()
	root := t.TempDir()
	for name, content := range files {
		testutil.WriteFile(t, filepath.Join(root, filepath.FromSlash(name)), content)
	}
	bundle := model.Bundle{ArchitecturePath: filepath.Join(root, "engmod.yml")}
	bundle.Architecture.AuthoredArchitecture.Machines = machines
	code, _ := codescan.InferCodeItems(bundle, root)
	checks, _ := codescan.InferVerificationChecks(bundle, model.RequirementsDocument{}, code, root)
	return machineVerificationDiagnostics(bundle, checks)
}

// A machine with no invariant is reported with or without evidence; an
// invariant without a current formal result is reported only when an evidence
// file exists, and a stale or missing result is no current result.
// Mutation: ignoring the evidence-exists flag reports the no-evidence case;
// counting a stale result as current hides the stale case.
// TRLC-LINKS: REQ-EMG-146, REQ-EMG-173
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestMachineVerificationDiagnostics(t *testing.T) {
	demo := func(invariants ...string) model.Machine {
		m := model.Machine{ID: "SM-DEMO"}
		for _, id := range invariants {
			m.Invariants = append(m.Invariants, model.MachineInvariant{ID: id})
		}
		return m
	}
	current := formalFixtureFiles([]formalFixtureEntry{{"REQ-F-001", "pass", "INV-F-001"}, {"REQ-F-002", "fail", "INV-F-002"}}, false)
	stale := formalFixtureFiles([]formalFixtureEntry{{"REQ-F-001", "pass", "INV-F-001"}}, true)
	cases := []struct {
		name     string
		machines []model.Machine
		files    map[string]string
		want     []string
	}{
		{"no machines", nil, current, []string{}},
		{"no invariant, no evidence", []model.Machine{demo()}, nil, []string{"authoredArchitecture.machines[0]"}},
		{"no invariant, evidence", []model.Machine{demo()}, current, []string{"authoredArchitecture.machines[0]"}},
		{"invariant, no evidence file", []model.Machine{demo("INV-F-001")}, nil, []string{}},
		{"passing and failing results are current", []model.Machine{demo("INV-F-001", "INV-F-002")}, current, []string{}},
		{"invariant without a result", []model.Machine{demo("INV-F-001", "INV-F-003")}, current, []string{"authoredArchitecture.machines[0].invariants[1]"}},
		{"stale result", []model.Machine{demo("INV-F-001")}, stale, []string{"authoredArchitecture.machines[0].invariants[0]"}},
		{"another machine's result", []model.Machine{{ID: "SM-OTHER", Invariants: []model.MachineInvariant{{ID: "INV-F-001"}}}}, current, []string{"authoredArchitecture.machines[0].invariants[0]"}},
	}
	for _, c := range cases {
		diags := machineFixture(t, c.machines, c.files)
		if got := pathsOf(diags, "behavior.machine_unverified"); !reflect.DeepEqual(got, c.want) {
			t.Errorf("%s: reported at %v, want %v", c.name, got, c.want)
		}
		requireShape(t, diags, "behavior.machine_unverified")
	}
}

// ValidateIntegrity carries the three checks: a missing owner, a requirement
// named in ENGMODEL-LINKS and a machine without invariant.
// Mutation: removing any of the three calls from integrityTail drops its code.
// TRLC-LINKS: REQ-EMG-170, REQ-EMG-171, REQ-EMG-173
// ENGMODEL-LINKS: FU-ALLOCATION-TRACE
func TestValidateIntegrityReportsConsistencyChecks(t *testing.T) {
	bundle, reqs := kindsBundle()
	bundle.Architecture.AuthoredArchitecture.Machines = []model.Machine{{ID: "SM-A"}}
	items := []codescan.CodeItem{
		{Kind: "source_file", Owner: "unresolved", Source: "a.go", Element: "a.go"},
		{Kind: "symbol", Source: "a.go:3", Element: "CODE-A", ModelLinks: []string{"REQ-A"}},
	}
	diags := ValidateIntegrity(bundle, reqs, items, nil)
	for _, code := range []string{"code.owner_unresolved", "code.model_link_kind_mismatch", "behavior.machine_unverified"} {
		if got := pathsOf(diags, code); len(got) != 1 {
			t.Errorf("%s reported at %v, want once", code, got)
		}
	}
}

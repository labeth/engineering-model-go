// renderInvariant generates a one-transition machine with Integer variables a
// and b, a Boolean p and a String s, and returns the rendered value of an
// invariant with the given expression.
func renderInvariant(t *testing.T, expr string) string {
	t.Helper()
	result := mustGenerate(t, expressionMachine(expr, "", ""))
	for _, line := range strings.Split(result.Files[0].Text, "\n") {
		if rest, ok := strings.CutPrefix(line, "  val inv_i = "); ok {
			return rest
		}
	}
	t.Fatalf("no invariant in\n%s", result.Files[0].Text)
	return ""
}

func expressionMachine(invariant, guard, effect string) model.Machine {
	m := model.Machine{
		ID: "SM-EXPR", Initial: "STATE-A",
		Variables: []model.MachineVariable{
			{Name: "a", Type: "Integer", Initial: 1}, {Name: "b", Type: "Integer", Initial: -2},
			{Name: "p", Type: "Boolean", Initial: false}, {Name: "s", Type: "String", Initial: "x"},
		},
		States:      []model.MachineState{{ID: "STATE-A"}, {ID: "STATE-B"}},
		Transitions: []model.MachineTransition{{ID: "TR-AB", From: "STATE-A", To: "STATE-B", Guard: guard, Effect: effect}},
	}
	if invariant != "" {
		m.Invariants = []model.MachineInvariant{{ID: "I", Expr: invariant}}
	}
	return m
}


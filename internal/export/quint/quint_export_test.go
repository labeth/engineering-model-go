func TestGenerationIsDeterministic(t *testing.T) {
	first := generateFixture(t)
	for i := 0; i < 20; i++ {
		again := generateFixture(t)
		if len(again.Files) != len(first.Files) || again.Files[0].Text != first.Files[0].Text {
			t.Fatalf("run %d produced different text", i)
		}
	}
	text := first.Files[0].Text
	if !strings.HasSuffix(text, "}\n") || strings.Contains(text, "\r") || strings.Contains(text, "\t") {
		t.Error("module must end with a newline and hold no CR or tab")
	}
	for i, line := range strings.Split(strings.TrimSuffix(text, "\n"), "\n") {
		if strings.TrimRight(line, " ") != line {
			t.Errorf("line %d has trailing white space: %q", i+1, line)
		}
	}
}


func TestOperatorRendering(t *testing.T) {
	for _, tc := range []struct{ src, want string }{
		{"a < b", "v_a < v_b"},
		{"a <= b and p", "(v_a <= v_b) and v_p"},
		{"p or p and p", "v_p or (v_p and v_p)"},
		{"(p or p) and p", "(v_p or v_p) and v_p"},
		{"p implies p implies p", "v_p implies (v_p implies v_p)"},
		{"not p", "not(v_p)"},
		{"not (a == b)", "not(v_a == v_b)"},
		{"not p and p", "not(v_p) and v_p"},
		{"-a < 0", "-(v_a) < 0"},
		{"a + b * 2 > 3 - a", "(v_a + (v_b * 2)) > (3 - v_a)"},
		{"a - (b - 1) != 0", "(v_a - (v_b - 1)) != 0"},
		{"(a - b) - 1 == 0", "((v_a - v_b) - 1) == 0"},
		{`s == "hello world"`, `v_s == "hello world"`},
		{`s != "back\\slash"`, `v_s != "back\slash"`},
		{"p == true", "v_p == true"},
		{"in_state(STATE-B) or in_state(STATE-A)", "(state == StateB) or (state == StateA)"},
		{"not in_state(STATE-A)", "not(state == StateA)"},
	} {
		if got := renderInvariant(t, tc.src); got != tc.want {
			t.Errorf("%q: got %q, want %q", tc.src, got, tc.want)
		}
	}
}


func generateFixture(t *testing.T) Result {
	t.Helper()
	result, err := GenerateFromFile(fixtureManifest)
	if err != nil {
		t.Fatalf("GenerateFromFile: %v\n%+v", err, result.Diagnostics)
	}
	return result
}

// bundleWith builds a bundle that carries only machines.
func bundleWith(machines ...model.Machine) model.Bundle {
	var bundle model.Bundle
	bundle.Architecture.AuthoredArchitecture.Machines = machines
	return bundle
}

func mustGenerate(t *testing.T, machines ...model.Machine) Result {
	t.Helper()
	result, err := Generate(bundleWith(machines...))
	if err != nil {
		t.Fatalf("Generate: %v\n%+v", err, result.Diagnostics)
	}
	return result
}

func diagnosticMessages(result Result) string {
	var parts []string
	for _, d := range result.Diagnostics {
		parts = append(parts, d.Code+" "+d.Path+" "+d.Message)
	}
	return strings.Join(parts, "\n")
}


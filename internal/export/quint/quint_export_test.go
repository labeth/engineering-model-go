func TestGoldenModuleOfFixture(t *testing.T) {
	result := generateFixture(t)
	if len(result.Files) != 1 {
		t.Fatalf("expected one module, got %d", len(result.Files))
	}
	file := result.Files[0]
	path := filepath.Join(goldenDir, file.Name)
	if os.Getenv("ENGMOD_UPDATE_GOLDEN") == "1" {
		if err := os.MkdirAll(goldenDir, 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(file.Text), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden (ENGMOD_UPDATE_GOLDEN=1 writes it): %v", err)
	}
	if file.Text != string(want) {
		t.Fatalf("generated module differs from %s (ENGMOD_UPDATE_GOLDEN=1 rewrites it)\n--- got\n%s\n--- want\n%s", path, file.Text, want)
	}
}


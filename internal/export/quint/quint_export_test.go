// The integration test runs the pinned Quint on the golden module. It is
// skipped unless ENGMOD_QUINT names the quint executable.
//
// TRLC-LINKS: REQ-EMG-141
func TestQuintAcceptsGeneratedModule(t *testing.T) {
	quint := os.Getenv("ENGMOD_QUINT")
	if quint == "" {
		t.Skip("ENGMOD_QUINT is not set")
	}
	file := generateFixture(t).Files[0]
	dir := t.TempDir()
	path := filepath.Join(dir, file.Name)
	if err := os.WriteFile(path, []byte(file.Text), 0o644); err != nil {
		t.Fatal(err)
	}
	if out, code := runQuint(t, quint, "typecheck", path); code != 0 {
		t.Fatalf("typecheck exit %d:\n%s", code, out)
	}
	for _, inv := range file.Invariants {
		out, code := runQuint(t, quint, "run", path, "--main="+file.Module, "--backend=typescript", "--invariant="+inv.Name,
			"--max-steps=20", "--max-samples=1000", "--seed=1")
		if code != 0 {
			t.Errorf("%s: run exit %d:\n%s", inv.Name, code, out)
		}
	}
	for _, witness := range file.Witnesses {
		// A witness is reachable when the negated witness is violated.
		out, code := runQuint(t, quint, "run", path, "--main="+file.Module, "--backend=typescript", "--witnesses="+witness,
			"--max-steps=20", "--max-samples=1000", "--seed=1")
		if code != 0 || !strings.Contains(out, witness) {
			t.Errorf("%s: run exit %d:\n%s", witness, code, out)
		}
	}

	// A false invariant must be reported as a violation (exit 1).
	broken := expressionMachine("a < 2", "a < 3", "a := a + 1")
	broken.ID = "SM-BROKEN"
	broken.Invariants[0].ID = "INV-BROKEN"
	result := mustGenerate(t, broken)
	brokenPath := filepath.Join(dir, result.Files[0].Name)
	if err := os.WriteFile(brokenPath, []byte(result.Files[0].Text), 0o644); err != nil {
		t.Fatal(err)
	}
	if out, code := runQuint(t, quint, "typecheck", brokenPath); code != 0 {
		t.Fatalf("typecheck of the broken module exit %d:\n%s", code, out)
	}
	out, code := runQuint(t, quint, "run", brokenPath, "--main=sm_broken", "--backend=typescript", "--invariant=inv_broken",
		"--max-steps=20", "--max-samples=1000", "--seed=1", "--verbosity=3")
	if code != 1 || !strings.Contains(out, `lastTransition: "TR-AB"`) {
		t.Fatalf("expected a violation with exit 1 naming TR-AB, got %d:\n%s", code, out)
	}
}

func runQuint(t *testing.T, quint string, args ...string) (string, int) {
	t.Helper()
	cmd := exec.Command(quint, args...)
	out, err := cmd.CombinedOutput()
	if err == nil {
		return string(out), 0
	}
	if exit, ok := err.(*exec.ExitError); ok {
		return string(out), exit.ExitCode()
	}
	t.Fatalf("run %s: %v", quint, err)
	return "", -1
}

// A module name is a file name, and Windows reserves the device names for
// files with any extension, so such a machine ID is refused everywhere.
//
// TRLC-LINKS: REQ-EMG-141
func TestMachineIDThatIsAWindowsDeviceNameIsRefused(t *testing.T) {
	for _, id := range []string{"CON", "prn", "Aux", "NUL", "COM1", "com9", "LPT1", "lpt9"} {
		m := expressionMachine("p", "", "")
		m.ID = id
		result, err := Generate(bundleWith(m))
		msgs := diagnosticMessages(result)
		if err == nil || len(result.Files) != 0 || !strings.Contains(msgs, "quint.name_collision") || !strings.Contains(msgs, "device name Windows reserves") {
			t.Errorf("%s: err %v files %d\n%s", id, err, len(result.Files), msgs)
		}
	}
	for _, id := range []string{"COM", "COM10", "CONSOLE", "LPT0", "SM-CON"} {
		m := expressionMachine("p", "", "")
		m.ID = id
		if _, err := Generate(bundleWith(m)); err != nil {
			t.Errorf("%s must be allowed: %v", id, err)
		}
	}
}

// A variable whose initial value fails is still declared, so only the root
// cause is reported and not one "undeclared variable" for every reader.
//
// TRLC-LINKS: REQ-EMG-141
func TestFailedVariableDeclarationReportsOnlyTheRootCause(t *testing.T) {
	for _, tc := range []struct {
		name   string
		mutate func(*model.Machine)
		code   string
	}{
		{"wrong initial value", func(m *model.Machine) { m.Variables[0].Initial = "one" }, "quint.type_mismatch"},
		{"unquotable string", func(m *model.Machine) { m.Variables[3].Initial = `say "hi"`; m.Invariants[0].Expr = `s == "x"` }, "quint.unsupported_string"},
		{"unknown type", func(m *model.Machine) { m.Variables[0].Type = "Float" }, "quint.invalid_machine"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			m := expressionMachine("a < 5 and s == \"x\"", "a < 3", "a := a + 1")
			m.Transitions = append(m.Transitions, model.MachineTransition{ID: "TR-BA", From: "STATE-B", To: "STATE-A", Guard: "a > 0 and s == \"x\"", Effect: "a := 0"})
			tc.mutate(&m)
			result, err := Generate(bundleWith(m))
			if err == nil {
				t.Fatal("expected an error")
			}
			var errors []string
			for _, d := range result.Diagnostics {
				if d.Severity == model.SemanticSeverityError {
					errors = append(errors, d.Code+" "+d.Path)
				}
			}
			if len(errors) != 1 || !strings.HasPrefix(errors[0], tc.code+" ") || !strings.Contains(errors[0], ".variables[") {
				t.Fatalf("want only the root cause %s, got %v", tc.code, errors)
			}
		})
	}
}

var hyphenInIdentifier = regexp.MustCompile(`[A-Za-z0-9_]-[A-Za-z0-9_]`)

// TRLC-LINKS: REQ-EMG-141
func TestDashesStayOutOfIdentifiers(t *testing.T) {
	result := mustGenerate(t, model.Machine{
		ID: "SM-A-B--C", Initial: "STATE-A-1",
		States:      []model.MachineState{{ID: "STATE-A-1", Name: "First\nstate"}, {ID: "STATE-A-2"}},
		Transitions: []model.MachineTransition{{ID: "TR-A-B-001", From: "STATE-A-1", To: "STATE-A-2", On: "EVT-X-Y"}},
		Invariants:  []model.MachineInvariant{{ID: "INV-A-B", Requirements: []string{"REQ-A-B"}, Expr: "in_state(STATE-A-1) or true"}},
	})
	file := result.Files[0]
	if file.Module != "sm_a_b_c" {
		t.Fatalf("module %q", file.Module)
	}
	for _, line := range strings.Split(file.Text, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "//") {
			continue
		}
		code := regexp.MustCompile(`"[^"]*"`).ReplaceAllString(line, `""`)
		if hyphenInIdentifier.MatchString(code) {
			t.Errorf("dash in identifier: %q", line)
		}
	}
	for _, want := range []string{
		"type State = StateA1 | StateA2\n", "// TR-A-B-001 (EVT-X-Y): First state -> STATE-A-2\n",
		"action tr_a_b_001 = all {\n", "lastTransition' = \"TR-A-B-001\",\n", "val inv_a_b = (state == StateA1) or true\n",
		"val wit_state_a_1 = state == StateA1\n", "// INV-A-B protects REQ-A-B\n",
	} {
		if !strings.Contains(file.Text, want) {
			t.Errorf("missing %q in\n%s", want, file.Text)
		}
	}
}

